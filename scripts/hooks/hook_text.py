"""Shell text for the suite pre-commit. Returns strings and does not write files."""

import re

from hooks.config import AIM, COGNITIVE, MAX_ARGS, MAINTAIN, REJECT


LOUD_LINE = (
    "SUITE GATES SKIPPED — SUITE_GATES_SKIP is set for this commit only. "
    "The length and complexity gates did not run. This value is not stored."
)
FAIL_PYTHON = "SUITE GATES FAILED CLOSED — python3 is not on PATH."
MARKER_LINE = "# suite-hook:set-hooks-path"

CONFIG_TEXT = f"""\
# suite-gates.cfg — created by scripts/hooks/install_gates.py because the file was absent.
# The integers below are the defaults. A later edit is the live ceiling for
# suite-installed sections only. Constraints, or the hook fails closed:
# reject > 200, reject > maintain > aim >= 0, cognitive >= 0, max_args >= 0.
# A whitespace-only file is malformed. It is not "missing, use defaults."
# This file does not retune a length hook this installer did not write.
# The installer does not git add this file.

[loc]
reject = {REJECT}
maintain = {MAINTAIN}
aim = {AIM}

[complexity]
cognitive = {COGNITIVE}
max_args = {MAX_ARGS}
"""

_LOC_BLOCK = """\
# >>> suite-hook:loc-gate >>>
# Honors a staged Python comment `# LOC-EXEMPT: <reason>` for the 500 reject only.
_loc="$_suite_gates_root/scripts/hooks/loc_gate.py"
if [ ! -f "$_loc" ]; then
  echo "SUITE GATES FAILED CLOSED — cannot start $_loc: not a file"
  _suite_gate_status=1
else
  python3 "$_loc" --staged
  if [ "$?" -ne 0 ]; then
    _suite_gate_status=1
  fi
fi
# <<< suite-hook:loc-gate <<<
"""

_COMPLEXITY_BLOCK = """\
# >>> suite-hook:complexity-gate >>>
_cog="$_suite_gates_root/scripts/hooks/complexity_gate.py"
if [ ! -f "$_cog" ]; then
  echo "SUITE GATES FAILED CLOSED — cannot start $_cog: not a file"
  _suite_gate_status=1
else
  python3 "$_cog" --staged
  if [ "$?" -ne 0 ]; then
    _suite_gate_status=1
  fi
fi
# <<< suite-hook:complexity-gate <<<
"""

_EXIT_RE = re.compile(r"^exit")


def shell_quote(value):
    """Single-quote a string for the shell. An embedded quote is ``'\\''``."""
    return "'" + str(value).replace("'", "'\\''") + "'"


def loc_block():
    return _LOC_BLOCK


def complexity_block():
    return _COMPLEXITY_BLOCK


def insert_marker(text):
    """Insert the hooksPath marker after the shebang when the substring is absent."""
    if MARKER_LINE in text:
        return text
    lines = text.splitlines(keepends=True)
    marker = MARKER_LINE + "\n"
    if lines and lines[0].startswith("#!"):
        lines.insert(1, marker)
    else:
        lines.insert(0, marker)
    return "".join(lines)


def splice(text, blocks):
    """Insert marked blocks before the last ``^exit`` line.

    Returns None when no line matches, so the caller writes nothing.
    """
    blocks = [block for block in blocks if block]
    if not blocks:
        return text
    lines = text.splitlines(keepends=True)
    index = None
    for i, line in enumerate(lines):
        if _EXIT_RE.match(line):
            index = i
    if index is None:
        return None
    chunk = "\n\n".join(block.strip("\n") for block in blocks) + "\n"
    lines.insert(index, chunk)
    return "".join(lines)


def render(suite_root, *, preserved=False, length=True, complexity=True, trampoline=None):
    """Return a pre-commit script.

    ``preserved`` keeps the case-4 sibling block. ``trampoline`` is the dormant
    hook to run first, instead of that sibling. A length section that is not
    installed becomes ``# suite-hook:loc-existing`` and does not call loc_gate.
    """
    lines = [
        "#!/bin/sh",
        "# suite-hook:chain",
        "# Generated by scripts/hooks/install_gates.py. Thresholds are not stored here.",
        "# Ceilings: .githooks/suite-gates.cfg. A missing path means the built-in defaults.",
        "",
    ]
    if length or complexity:
        lines.append(f"_suite_gates_root={shell_quote(suite_root)}")
    if trampoline:
        lines.append(f"_preserved={shell_quote(trampoline)}")
        lines.append("")
        lines.extend([
            '"$_preserved" "$@"',
            "_preserved_status=$?",
            'if [ "$_preserved_status" -ne 0 ]; then',
            '  exit "$_preserved_status"',
            "fi",
        ])
    elif preserved:
        lines.append(
            '_preserved=$(CDPATH= cd -- "$(dirname "$0")" && pwd)/pre-commit.suite-preserved'
        )
        lines.append("")
        lines.extend([
            'if [ -f "$_preserved" ]; then',
            '  "$_preserved" "$@"',
            "  _preserved_status=$?",
            '  if [ "$_preserved_status" -ne 0 ]; then',
            '    exit "$_preserved_status"',
            "  fi",
            "fi",
        ])
    if length or complexity:
        lines.append("")
        lines.extend([
            'if [ -n "${SUITE_GATES_SKIP:-}" ]; then',
            f'  echo "{LOUD_LINE}"',
            "  exit 0",
            "fi",
            "",
            "if ! command -v python3 >/dev/null 2>&1; then",
            f'  echo "{FAIL_PYTHON}"',
            "  exit 1",
            "fi",
            "",
            "_suite_gate_status=0",
            "",
        ])
        if length:
            lines.append(_LOC_BLOCK.rstrip("\n"))
        else:
            lines.append("# suite-hook:loc-existing")
        if complexity:
            lines.append("")
            lines.append(_COMPLEXITY_BLOCK.rstrip("\n"))
        lines.append("")
        lines.append('exit "$_suite_gate_status"')
    else:
        lines.append("")
        lines.append("exit 0")
    text = "\n".join(lines) + "\n"
    if MARKER_LINE in text:
        raise RuntimeError("generated hook text must not contain the hooksPath marker")
    return text
